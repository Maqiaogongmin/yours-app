import 'dart:io';

const String _targetRoot = '.dart_tool/harmony-flutter-packages';

const List<_HarmonyPackageSource> _sources = <_HarmonyPackageSource>[
  _HarmonyPackageSource(
    name: 'path_provider',
    repository: 'https://gitcode.com/openharmony-tpc/flutter_packages.git',
    ref: 'br_path_provider-v2.1.5_ohos',
    targetPath: '$_targetRoot/path_provider',
    sparsePaths: <String>[
      'packages/path_provider/path_provider',
      'packages/path_provider/path_provider_ohos',
    ],
    expectedPackagePath: 'packages/path_provider/path_provider/pubspec.yaml',
  ),
  _HarmonyPackageSource(
    name: 'shared_preferences',
    repository: 'https://gitcode.com/openharmony-tpc/flutter_packages.git',
    ref: 'br_shared_preferences-v2.5.4_ohos',
    targetPath: '$_targetRoot/shared_preferences',
    sparsePaths: <String>[
      'packages/shared_preferences/shared_preferences',
      'packages/shared_preferences/shared_preferences_ohos',
    ],
    expectedPackagePath: 'packages/shared_preferences/shared_preferences/pubspec.yaml',
  ),
  _HarmonyPackageSource(
    name: 'sqlcipher_flutter_libs',
    repository: 'https://gitcode.com/tech-ming/sqlite3-ohos.dart.git',
    ref: 'main',
    targetPath: '$_targetRoot/sqlite3-ohos',
    sparsePaths: <String>['sqlcipher_flutter_libs'],
    expectedPackagePath: 'sqlcipher_flutter_libs/pubspec.yaml',
  ),
];

Future<void> main(List<String> arguments) async {
  final bool refresh = arguments.contains('--refresh');

  for (final source in _sources) {
    await _ensureSource(source, refresh: refresh);
  }

  final overrides = File('pubspec_overrides.yaml');
  overrides.writeAsStringSync('''
# Generated by `dart run tool/bootstrap_harmony_flutter_deps.dart`.
# Keep this file local; it points Flutter-OH at OHOS package checkouts under
# .dart_tool instead of making normal iOS/Android dependency resolution depend
# on HarmonyOS-only package forks.
dependency_overrides:
  path_provider:
    path: .dart_tool/harmony-flutter-packages/path_provider/packages/path_provider/path_provider
  path_provider_ohos:
    path: .dart_tool/harmony-flutter-packages/path_provider/packages/path_provider/path_provider_ohos
  path_provider_foundation: 2.5.1
  shared_preferences:
    path: .dart_tool/harmony-flutter-packages/shared_preferences/packages/shared_preferences/shared_preferences
  shared_preferences_ohos:
    path: .dart_tool/harmony-flutter-packages/shared_preferences/packages/shared_preferences/shared_preferences_ohos
  sqlcipher_flutter_libs:
    path: .dart_tool/harmony-flutter-packages/sqlite3-ohos/sqlcipher_flutter_libs
''');
  stdout.writeln('Wrote ${overrides.path}');
}

Future<void> _ensureSource(
  _HarmonyPackageSource source, {
  required bool refresh,
}) async {
  final directory = Directory(source.targetPath);
  final packageFile = File('${source.targetPath}/${source.expectedPackagePath}');

  if (refresh && directory.existsSync()) {
    directory.deleteSync(recursive: true);
  }

  if (packageFile.existsSync()) {
    stdout.writeln('Using existing ${source.name} at ${source.targetPath}');
    return;
  }

  directory.parent.createSync(recursive: true);
  stdout.writeln('Cloning ${source.name} from ${source.repository}#${source.ref}');
  await _runGit(<String>[
    'clone',
    '--depth',
    '1',
    '--filter=blob:none',
    '--sparse',
    '--branch',
    source.ref,
    source.repository,
    source.targetPath,
  ]);
  await _runGit(<String>[
    '-C',
    source.targetPath,
    'sparse-checkout',
    'set',
    ...source.sparsePaths,
  ]);

  if (!packageFile.existsSync()) {
    throw StateError(
      'Expected ${source.name} package at ${packageFile.path}, but it was not created.',
    );
  }
}

Future<void> _runGit(List<String> arguments) async {
  final result = await Process.run('git', arguments);
  if (result.exitCode != 0) {
    stderr.writeln(result.stdout);
    stderr.writeln(result.stderr);
    throw ProcessException('git', arguments, 'git command failed', result.exitCode);
  }
}

class _HarmonyPackageSource {
  const _HarmonyPackageSource({
    required this.name,
    required this.repository,
    required this.ref,
    required this.targetPath,
    required this.sparsePaths,
    required this.expectedPackagePath,
  });

  final String name;
  final String repository;
  final String ref;
  final String targetPath;
  final List<String> sparsePaths;
  final String expectedPackagePath;
}
